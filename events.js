function pickPartnerQuote(gender, tag) {
  const gPool = PARTNER_TAG_QUOTES[gender] || PARTNER_TAG_QUOTES.female;
  const tagList = gPool[tag] || gPool["平日昼"];
  return tagList[Math.floor(Math.random() * tagList.length)];
}

